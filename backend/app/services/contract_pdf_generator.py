def _get_pdf_semaphore() -> asyncio.Semaphore:
    global _PDF_SEMAPHORE
    if _PDF_SEMAPHORE is None:
        _PDF_SEMAPHORE = asyncio.Semaphore(2)
    return _PDF_SEMAPHORE

